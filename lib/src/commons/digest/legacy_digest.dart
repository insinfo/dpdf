  static int _function(int round, int x, int y, int z) => switch (round) {
        0 => x ^ y ^ z,
        1 => (x & y) | (~x & z),
        2 => (x | ~y) ^ z,
        3 => (x & z) | (y & ~z),
        4 => x ^ (y | ~z),
        _ => throw StateError('Invalid RIPEMD round'),
      };
  static Uint8List _ripemd(Uint8List input, int bits) {
    final padded = Uint8List(((input.length + 9 + 63) ~/ 64) * 64)
      ..setRange(0, input.length, input);
    padded[input.length] = 128;
    final data = ByteData.sublistView(padded);
    data.setUint32(
        padded.length - 8, (input.length * 8) & _mask, Endian.little);
    data.setUint32(padded.length - 4, input.length >> 29, Endian.little);
    var hash = [
      0x67452301,
      0xefcdab89,
      0x98badcfe,
      0x10325476,
      if (bits == 160) 0xc3d2e1f0,
      if (bits == 256) ...[0x76543210, 0xfedcba98, 0x89abcdef, 0x01234567]
    ];
    final count = bits == 160 ? 5 : 4;
    final constants = [
      [0, 0x5a827999, 0x6ed9eba1, 0x8f1bbcdc, 0xa953fd4e],
      [0x50a28be6, 0x5c4dd124, 0x6d703ef3, bits == 160 ? 0x7a6d76e9 : 0, 0],
    ];
    for (var block = 0; block < padded.length; block += 64) {
      final words = List.generate(
          16, (i) => data.getUint32(block + i * 4, Endian.little));
      final lanes = [
        hash.sublist(0, count),
        bits == 256 ? hash.sublist(4) : hash.sublist(0, count)
      ];
      for (var step = 0; step < count * 16; step++) {
        for (var lane = 0; lane < 2; lane++) {
          final v = lanes[lane];
          var next = _rol(
              v[0] +
                  _function(lane == 0 ? step ~/ 16 : count - 1 - step ~/ 16,
                      v[1], v[2], v[3]) +
                  words[_wordOrder[lane][step]] +
                  constants[lane][step ~/ 16],
              _rotation[lane][step]);
          if (bits == 160) {
            next = (next + v[4]) & _mask;
            lanes[lane] = [v[4], next, v[1], _rol(v[2], 10), v[3]];
          } else {
            lanes[lane] = [v[3], next, v[1], v[2]];
          }
        }
        if (bits == 256 && step % 16 == 15) {
          final i = step ~/ 16, temp = lanes[0][i];
          lanes[0][i] = lanes[1][i];
          lanes[1][i] = temp;
        }
      }
      if (bits == 256) {
        hash =
            List.generate(8, (i) => (hash[i] + lanes[i ~/ 4][i % 4]) & _mask);
      } else {
        hash = List.generate(
            count,
            (i) =>
                (hash[(i + 1) % count] +
                    lanes[0][(i + 2) % count] +
                    lanes[1][(i + 3) % count]) &
                _mask);
      }
    }
    final result = ByteData(bits ~/ 8);
    for (var i = 0; i < hash.length; i++) {
      result.setUint32(i * 4, hash[i], Endian.little);
    }
    return result.buffer.asUint8List();
  }

