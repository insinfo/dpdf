  static Uint8List _md2(Uint8List input) {
    final pad = 16 - input.length % 16;
    final blocks = Uint8List.fromList([...input, ...List.filled(pad, pad)]);
    final checksum = Uint8List(16);
    var previous = 0;
    for (var position = 0; position < blocks.length; position++) {
      final index = position % 16;
      checksum[index] ^= _piPermutation[blocks[position] ^ previous];
      previous = checksum[index];
    }
    final encoded = Uint8List.fromList([...blocks, ...checksum]);
    final state = Uint8List(48);
    for (var offset = 0; offset < encoded.length; offset += 16) {
      state.setRange(16, 32, encoded, offset);
      for (var index = 0; index < 16; index++) {
        state[32 + index] = state[index] ^ state[16 + index];
      }
      var feedback = 0;
      for (var round = 0; round < 18; round++) {
        for (var index = 0; index < 48; index++) {
          state[index] ^= _piPermutation[feedback];
          feedback = state[index];
        }
        feedback = (feedback + round) & 255;
      }
    }
    return state.sublist(0, 16);
  }
