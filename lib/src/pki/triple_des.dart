import 'dart:typed_data';

/// Recovery of legacy DES-EDE CBC containers; not an encryption API.
/// Bit permutations and substitution tables follow NIST FIPS 46-3.
abstract final class TripleDes {
  static Uint8List decryptCbc(Uint8List ciphertext,
      {required Uint8List key, required Uint8List iv}) {
    if (key.length != 24 || iv.length != 8) {
      throw ArgumentError('Expected a 24-byte key and eight-byte IV.');
    }
    if (ciphertext.isEmpty || ciphertext.length % 8 != 0) {
      throw ArgumentError('Ciphertext must contain complete blocks.');
    }
    final keys = [
      for (var n = 0; n < 3; n++) _schedule(key.sublist(n * 8, n * 8 + 8))
    ];
    final result = Uint8List(ciphertext.length);
    for (var offset = 0; offset < ciphertext.length; offset += 8) {
      var block = _bits(ciphertext.sublist(offset, offset + 8));
      block = _des(block, keys[2].reversed.toList());
      block = _des(block, keys[1]);
      block = _des(block, keys[0].reversed.toList());
      for (var byte = 0; byte < 8; byte++) {
        var value = 0;
        for (var bit = 0; bit < 8; bit++) {
          value = value * 2 + block[byte * 8 + bit];
        }
        result[offset + byte] =
            value ^ (offset == 0 ? iv[byte] : ciphertext[offset + byte - 8]);
      }
    }
    final padding = result.last;
    if (padding < 1 || padding > 8)
      throw FormatException('Invalid Triple DES padding.');
    var mismatch = 0;
    for (var n = result.length - padding; n < result.length; n++) {
      mismatch |= result[n] ^ padding;
    }
    if (mismatch != 0) throw FormatException('Invalid Triple DES padding.');
    return Uint8List.fromList(result.sublist(0, result.length - padding));
  }

  static List<int> _bits(List<int> bytes) => [
        for (final b in bytes)
          for (var n = 7; n >= 0; n--) (b >> n) & 1
      ];
  static List<int> _select(List<int> bits, List<int> positions) =>
      [for (final p in positions) bits[p - 1]];
  static List<List<int>> _schedule(List<int> bytes) {
    final chosen = _select(_bits(bytes), _pc1);
    var left = chosen.sublist(0, 28), right = chosen.sublist(28);
    final keys = <List<int>>[];
    for (var round = 0; round < 16; round++) {
      final shift = const [0, 1, 8, 15].contains(round) ? 1 : 2;
      left = [...left.skip(shift), ...left.take(shift)];
      right = [...right.skip(shift), ...right.take(shift)];
      keys.add(_select([...left, ...right], _pc2));
    }
    return keys;
  }

  static List<int> _des(List<int> block, List<List<int>> keys) {
    final initial = _select(block, _ip);
    var left = initial.sublist(0, 32), right = initial.sublist(32);
    for (final key in keys) {
      final expanded = [
        for (var group = 0; group < 8; group++)
          for (var bit = 0; bit < 6; bit++) right[(group * 4 + bit + 31) % 32]
      ];
      for (var n = 0; n < 48; n++) {
        expanded[n] ^= key[n];
      }
      final substitution = <int>[];
      for (var box = 0; box < 8; box++) {
        final start = box * 6;
        final row = expanded[start] * 2 + expanded[start + 5];
        var column = 0;
        for (var n = 1; n < 5; n++) {
          column = column * 2 + expanded[start + n];
        }
        final value = _sboxes[box][row * 16 + column];
        substitution
            .addAll([for (var bit = 3; bit >= 0; bit--) (value >> bit) & 1]);
      }
      final mixed = _select(substitution, _p);
      final next = [for (var n = 0; n < 32; n++) left[n] ^ mixed[n]];
      left = right;
      right = next;
    }
    final swapped = [...right, ...left];
    final result = List<int>.filled(64, 0);
    for (var n = 0; n < 64; n++) {
      result[_ip[n] - 1] = swapped[n];
    }
    return result;
  }

